#!/bin/bash
# Regenerates THIRD_PARTY_LICENSES.md from what is ACTUALLY DISTRIBUTED:
#
#   - the Go modules linked into the binary, read back off a probe build with
#     `go version -m`, so the list can never drift from go.mod guesswork;
#   - the third-party front-end files embedded from web/: the React,
#     ReactDOM and Babel scripts under web/vendor/ and the Inter and
#     JetBrains Mono fonts under web/fonts/. Their upstream licence texts are
#     kept beside them (web/vendor/*.LICENSE, web/fonts/*LICENSE*.txt and
#     *OFL*.txt) — whoever updates an asset updates its licence in the same
#     commit. babel.min.js is a bundle of many packages, so it also has
#     web/vendor/babel-standalone.THIRD-PARTY.txt, written by
#     scripts/babel-bundle-licenses.py from upstream's source map. Anything
#     else third-party embedded under web/ later must be given a licence
#     file there and an emit_asset line below.
#
# For each module it emits EVERY license/notice file that module ships (some
# carry several — modernc.org/libc has LICENSE plus LICENSE-3RD-PARTY.md), and
# if none of them carries a copyright LINE it extracts one from the module's
# source, so MIT/BSD attribution is never silently dropped. A module can also
# carry code under another license in one of its packages, with the license
# beside it (go-jose's json package is a copy of Go's encoding/json): the
# license files in the directory of every package that is linked in are
# emitted too.
#
# Usage: scripts/gen-third-party-licenses.sh [output-path]
#   Default output THIRD_PARTY_LICENSES.md. `make notices-check` runs it to a
#   temp file and diffs, so a stale committed copy fails the release.
set -euo pipefail
# Byte-order sorting/grep everywhere so the output is identical regardless of
# the runner's locale (a UTF-8 collation would order some inputs differently).
export LC_ALL=C
cd "$(git rev-parse --show-toplevel)"

OUT=${1:-THIRD_PARTY_LICENSES.md}
MODCACHE=$(go env GOMODCACHE)
PROBE=$(mktemp)
trap 'rm -f "$PROBE"' EXIT

CGO_ENABLED=0 go build -o "$PROBE" .

# emit_file <path> <heading>: a titled fenced block, GUARANTEEING a trailing
# newline before the closing fence (a license lacking a final newline would
# otherwise glue ``` onto its last line and break the Markdown).
emit_file() {
	local path=$1 heading=$2
	echo
	echo "### $heading"
	echo
	echo '```'
	cat "$path"
	[[ -n "$(tail -c1 "$path")" ]] && echo # add a newline only if the file lacks one
	echo '```'
}

# license_files <dir>: every license/notice/authors file in the directory
# itself, sorted. Source files are not licenses, whatever they are called
# (pgx has a notice_response.go).
license_files() {
	local dir=$1
	find "$dir" -maxdepth 1 -type f ! -name '*.go' \( \
		-iname 'LICENSE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \
		-o -iname 'PATENTS*' -o -iname 'AUTHORS*' -o -iname '*-LICENSE' -o -iname 'OFL*' \
		\) | sort
}

emit_module() {
	local title=$1 dir=$2
	echo
	echo "---"
	echo
	echo "## $title"
	local found=0 has_copyright=0 f
	while IFS= read -r f; do
		[[ -z "$f" ]] && continue
		found=1
		emit_file "$f" "$(basename "$f")"
		# A real copyright LINE carries a year — the MIT boilerplate phrase
		# "the above copyright notice" does not, so it must not mask a
		# genuinely missing notice.
		if grep -qiE 'copyright.*[12][0-9]{3}' "$f"; then has_copyright=1; fi
	done < <(license_files "$dir")
	if [[ "$found" = 0 ]]; then
		echo "ERROR: no license file found in $dir" >&2
		exit 1
	fi
	if [[ "$has_copyright" = 0 ]]; then
		local cline
		# Walk .go files in SORTED order (not grep -r's readdir order) so the
		# "first copyright line" is deterministic across machines — otherwise
		# the notices-check gate fails on an unrelated runner.
		cline=$(find "$dir" -name '*.go' -type f 2>/dev/null | sort \
			| xargs -r grep -hi copyright 2>/dev/null \
			| grep -m1 -E '[12][0-9]{3}' | sed 's#^[[:space:]/*]*##' || true)
		if [[ -n "$cline" ]]; then
			echo
			echo "### Copyright (from source headers)"
			echo
			echo '```'
			echo "$cline"
			echo '```'
		fi
	fi
}

{
	echo "# Third-party licenses"
	echo
	echo "ansbui itself is licensed under the GNU AGPL-3.0-or-later (see LICENSE)."
	echo "The distributed binary statically links the Go standard library and the Go"
	echo "modules below, and embeds the front-end scripts and fonts listed after them."
	echo "Every license and notice file each one ships is reproduced here in full."
	echo
	echo "Generated by scripts/gen-third-party-licenses.sh — regenerate after any"
	echo "dependency or bundled-asset change (\`make notices-check\`, run by the"
	echo "release workflow, fails if this is stale); do not edit by hand."

	# The Go standard library and runtime are statically linked in, but
	# `go version -m` lists only third-party modules — emit GOROOT's license
	# (and the PATENTS grant) explicitly.
	emit_module "Go standard library and runtime (BSD-3-Clause)" "$(go env GOROOT)"

	# Directories of the linked packages, for the license files that sit
	# beside a package and not at its module's root.
	PKGDIRS=$(CGO_ENABLED=0 go list -deps -f '{{if .Module}}{{.Dir}}{{end}}' . | sort -u)

	go version -m "$PROBE" | awk '$1=="dep"{print $2"@"$3}' | sort | while IFS= read -r mod; do
		emit_module "$mod" "$MODCACHE/$mod"
		while IFS= read -r pkgdir; do
			[[ "$pkgdir" == "$MODCACHE/$mod"/* ]] || continue
			while IFS= read -r f; do
				[[ -z "$f" ]] && continue
				emit_file "$f" "${f#"$MODCACHE/$mod"/}"
			done < <(license_files "$pkgdir")
		done <<<"$PKGDIRS"
	done

	# Embedded front-end scripts. Each title names the version, which is
	# also recorded with the file's checksum in web/index.html.
	emit_asset() {
		local title=$1 note=$2
		shift 2
		echo
		echo "---"
		echo
		echo "## Embedded asset: $title"
		if [[ -n "$note" ]]; then
			echo
			echo "$note"
		fi
		local f
		for f in "$@"; do
			[[ -e "$f" ]] || { echo "ERROR: missing license file $f" >&2; exit 1; }
			emit_file "$f" "$(basename "$f")"
		done
	}

	emit_asset "React 18.3.1 (MIT) — web/vendor/react.production.min.js" "" \
		web/vendor/react.LICENSE
	emit_asset "ReactDOM 18.3.1 (MIT) — web/vendor/react-dom.production.min.js" \
		"The file also contains React's scheduler (same copyright and license) and a snippet marked in the file as \"Modernizr 3.0.0pre (Custom Build) | MIT\"." \
		web/vendor/react-dom.LICENSE
	# babel.min.js bundles other packages besides Babel's own; the second
	# file lists each of them with its licence. It is produced from the
	# source map upstream publishes (scripts/babel-bundle-licenses.py) and
	# must be regenerated in the commit that replaces babel.min.js.
	emit_asset "@babel/standalone 7.29.14 (MIT) — web/vendor/babel.min.js" \
		"Babel's single-file browser build. The first text is Babel's own license. The second lists the other packages bundled into the file (MIT, ISC, BSD-2-Clause and, for the caniuse-lite browser data, CC-BY-4.0), each with the license it ships." \
		web/vendor/babel-standalone.LICENSE web/vendor/babel-standalone.THIRD-PARTY.txt

	# The web fonts served from web/fonts (not Go modules).
	emit_asset "Inter 4.1 (SIL Open Font License 1.1) — web/fonts/InterVariable.woff2" "" \
		web/fonts/Inter-LICENSE.txt
	emit_asset "JetBrains Mono 2.304 (SIL Open Font License 1.1) — web/fonts/JetBrainsMono-*.woff2" "" \
		web/fonts/JetBrainsMono-OFL.txt
} >"$OUT"

echo "wrote $OUT ($(wc -c <"$OUT") bytes)"
